import fs from "node:fs";
import path from "node:path";
import { declaration } from "./ast.mjs";

export const locales = ["pt-BR", "en-US", "ja-JP", "es-ES", "fr-FR", "de-DE"];
export const definitions = [
  ["designStrings", "I18N_DICTIONARY"], ["catalogStrings", "CATALOG_STRINGS"],
  ["playbackStrings", "PLAYBACK_STRINGS"], ["unifiedCatalogStrings", "UNIFIED_CATALOG_STRINGS"],
];
const flatten = (value, prefix = "") => typeof value === "string" ? [[prefix, value]] : value && typeof value === "object" ? Object.entries(value).flatMap(([key, item]) => flatten(item, prefix ? `${prefix}.${key}` : key)) : [];
export function dictionaries(root) {
  const texts = new Map(), all = [];
  for (const [module, name] of definitions) {
    const values = declaration(fs.readFileSync(path.join(root, `resources/js/lib/${module}.ts`), "utf8"), name);
    for (const [key, value] of flatten(values["pt-BR"])) {
      const translated = Object.fromEntries(locales.map(locale => [locale, flatten(values[locale]).find(([path]) => path === key)?.[1]]));
      if (Object.values(translated).some(item => typeof item !== "string" || !item.trim())) throw Error(`Missing translation: ${name}:${key}`);
      const entry = { id: `${name}:${key}`, values: translated };
      all.push(entry);
      for (const text of new Set(Object.values(translated))) {
        if (!texts.has(text)) texts.set(text, []);
        texts.get(text).push(entry);
      }
    }
  }
  const themes = declaration(fs.readFileSync(path.join(root, "resources/js/lib/designStrings.ts"), "utf8"), "THEME_PALETTES");
  return { texts, all, themes };
}

export function presentationBridge() {
  return `// Generated by scripts/refactor.py. Dictionary values remain in their single source.\nimport { useDesignTheme } from "../context/ThemeContext";\n${definitions.map(([module, name]) => `import { ${name} } from "./${module}";`).join("\n")}\nconst collections: Record<string, any> = { ${definitions.map(([, name]) => name).join(", ")} };\nexport function usePresentation() {\n  const { language, tokens } = useDesignTheme();\n  return {\n    text(id: string): string {\n      const [collection, key] = id.split(":");\n      let value: any = collections[collection]?.[language];\n      for (const part of (key || "").split(".")) value = value && Object.hasOwn(value, part) ? value[part] : undefined;\n      if (typeof value !== "string") throw new Error("Missing presentation string: " + id);\n      return value;\n    },\n    color(id: string): string {\n      const colors = tokens.colors as unknown as Record<string, string>;\n      if (!Object.hasOwn(colors, id)) throw new Error("Missing presentation token: " + id);\n      return colors[id];\n    },\n  };\n}\n`;
}
