import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { emptyRegistry } from "./work-registry.mjs";
import { assignIdentity } from "./assign-identities.mjs";
import { publishGeneration } from "./publish-generation.mjs";
import { loadCatalog } from "./load-catalog.mjs";
import { auditGeneration } from "./audit-generation.mjs";
import { loadGeneration } from "./load-generation.mjs";

test("partitioned publication retains legacy aliases and publishes its manifest only after every partition validates", async t => {
  const parent = fs.realpathSync(os.tmpdir()), directory = fs.mkdtempSync(path.join(parent, "anirium-generation-"));
  t.after(() => { assert.equal(path.dirname(fs.realpathSync(directory)), parent); fs.rmSync(directory, { recursive: true }); });
  const registry = emptyRegistry();
  const legacy = [{ mal_id: 1, title: "Anime" }, { mal_id: 1, entity_type: "MANGA", title: "Manga" }];
  const rows = legacy.map(row => assignIdentity(row, registry));
  rows.push(assignIdentity({ entity_type: "NOVEL", title: "Novel", external_ids_json: JSON.stringify([{ provider: "mangabaka", media: "manga", id: "1" }]) }, registry));
  const first = await publishGeneration(rows, legacy, directory, { chunkSize: 1 });
  const progress = [];
  assert.equal((await auditGeneration(directory, { registry, onProgress: value => progress.push(value) })).works, 3);
  assert.equal(progress[0].stage, "lookup");
  assert.equal(progress[0].worksChecked, 0);
  assert.deepEqual(progress.at(-1), { stage: "verified", generation: first.generation, partitionsChecked: 3, partitionsTotal: 3, worksChecked: 3, worksTotal: 3 });
  assert.deepEqual(progress.filter(value => value.stage === "partitions").map(value => value.partitionsChecked), [0, 1, 1, 2, 2, 3]);
  assert.equal((await loadGeneration(directory, registry)).length, 3);
  assert.deepEqual(first.files.map(file => file.media), ["anime", "manga", "novel"]);
  const lookup = JSON.parse(fs.readFileSync(path.join(directory, first.lookup.url.slice(6))));
  assert.equal(lookup["anime:1"].work_id, rows[0].work_id);
  assert.equal(lookup["manga:1"].work_id, rows[1].work_id);
  for (const file of first.files) assert.equal((await loadCatalog(path.join(directory, file.url.slice(6)))).rows.length, 1);
  const manifest = fs.readFileSync(path.join(directory, "catalog.manifest.json"));
  await assert.rejects(publishGeneration([rows[0], { ...rows[1], invalid: NaN }, rows[2]], rows, directory, { chunkSize: 1 }), /Invalid catalog column/);
  assert.deepEqual(fs.readFileSync(path.join(directory, "catalog.manifest.json")), manifest);
  fs.appendFileSync(path.join(directory, first.files[0].url.slice(6)), "corrupt");
  const failedProgress = [];
  await assert.rejects(auditGeneration(directory, { registry, onProgress: value => failedProgress.push(value) }), /checksum mismatch/);
  assert.equal(failedProgress.some(value => value.stage === "verified"), false);
  assert.equal(failedProgress.at(-1).partitionsChecked, 0);
});
