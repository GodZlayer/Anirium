import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createHash } from "node:crypto";
import { loadFillerSnapshot } from "./filler-snapshot-source.mjs";

test("snapshot cache validates bytes, skips unchanged assets and retains last good data offline", async t => {
  const parent = fs.realpathSync(os.tmpdir());
  const directory = fs.mkdtempSync(path.join(parent, "anirium-snapshot-source-"));
  t.after(() => { assert.equal(path.dirname(fs.realpathSync(directory)), parent); fs.rmSync(directory, { recursive: true }); });
  let clock = Date.parse("2026-10-21T00:00:00Z"), calls = 0;
  const content = JSON.stringify({ generated: "2026-10-20T00:00:00Z", shows: {} }, null, 2) + "\n";
  const asset = { name: "fillers.json", size: Buffer.byteLength(content), digest: "sha256:" + createHash("sha256").update(content).digest("hex"), browser_download_url: "https://github.com/cedya77/anime-offline-database/releases/download/fillers/fillers.json" };
  const options = { directory, now: () => clock, request: async url => { calls++; return url.includes("api.github.com") ? Response.json({ assets: [asset] }) : new Response(content); } };
  const original = await loadFillerSnapshot(options);
  assert.equal(original.stale, false);
  assert.equal(original.provenance.observedAt, "2026-10-20T00:00:00Z");
  assert.equal(original.provenance.license, undefined);
  assert.equal(original.provenance.repository_license, "ODbL-1.0 + DbCL-1.0");
  assert.equal(original.provenance.repository_attribution.length, 2);
  assert.equal(original.provenance.upstream.license, null);
  assert.equal(original.provenance.upstream.terms_verified, false);
  assert.equal(calls, 2);
  await loadFillerSnapshot(options);
  assert.equal(calls, 2);
  clock += 7 * 3600000;
  const unchanged = await loadFillerSnapshot(options);
  assert.equal(calls, 3);
  assert.equal(unchanged.stale, false);
  clock += 7 * 3600000;
  const stale = await loadFillerSnapshot({ ...options, request: async () => new Response(null, { status: 503 }) });
  assert.equal(stale.stale, true);
  assert.deepEqual(stale.snapshot, original.snapshot);
  assert.equal(stale.provenance.observedAt, original.provenance.observedAt);
  assert.equal(stale.provenance.checkedAt, unchanged.provenance.checkedAt);
  fs.writeFileSync(path.join(directory, `${asset.digest.slice(7)}.json`), "tampered");
  const invalid = await loadFillerSnapshot({ ...options, request: async () => new Response(null, { status: 503 }) });
  assert.equal(invalid.snapshot, undefined);
});

test("legacy cache provenance is clarified without changing observation dates or downloading again", async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "anirium-filler-legacy-"));
  t.after(() => fs.rmSync(directory, { recursive: true }));
  const snapshot = JSON.stringify({ generated: "2026-10-19T00:00:00Z", shows: {} });
  const digest = "sha256:" + createHash("sha256").update(snapshot).digest("hex");
  const saved = { digest, checkedAt: "2026-10-21T00:00:00Z", license: "ODbL-1.0 + DbCL-1.0" };
  fs.writeFileSync(path.join(directory, digest.slice(7) + ".json"), snapshot);
  const pointer = path.join(directory, "filler-source.json");
  fs.writeFileSync(pointer, JSON.stringify(saved));
  const result = await loadFillerSnapshot({ directory, now: () => Date.parse("2026-10-21T01:00:00Z"), request: async () => assert.fail("fresh cache must not use network") });
  assert.equal(result.provenance.checkedAt, saved.checkedAt);
  assert.equal(result.provenance.observedAt, "2026-10-19T00:00:00Z");
  assert.equal(result.provenance.digest, digest);
  assert.equal(result.provenance.license, undefined);
  assert.equal(result.provenance.upstream.license, null);
  assert.deepEqual(JSON.parse(fs.readFileSync(pointer)), saved);
});
